export function getCourseById(id) {
  return courses.find((course) => course.id === id)
}

export function getRelatedCourses(course, limit = 4) {
  return courses
    .filter((item) => item.id !== course.id)
    .sort((a, b) => {
      const scoreA = (a.category === course.category ? 2 : 0) + (a.language === course.language ? 1 : 0)
      const scoreB = (b.category === course.category ? 2 : 0) + (b.language === course.language ? 1 : 0)
      return scoreB - scoreA || b.rating - a.rating
    })
    .slice(0, limit)
}
