  sections.map((section, sIndex) => ({
    title: section[0],
    lessons: section.slice(1).map((title, lIndex) => ({
      title,
      duration: `${8 + ((sIndex * 3 + lIndex) % 9)}:${String(10 + ((sIndex + lIndex * 7) % 45)).padStart(2, '0')}`,
      preview: sIndex === 0 && lIndex === 0,
    })),
  }))

